"""
summarize_v5.py — the reported results, from the frozen v5 protocol (docs/12_frozen_protocol.md).

Reads only generated files:
  code/models_v5/<set>/final_eval.json          evaluate_v5.py --stage final   (final-test partition, final-test bank)
  results_v5/agents/<set>/seed_<n>/eval_results.json   evaluate_agents.py      (final-test bank, greedy, 2,000 probes)
Writes docs/v5_results.md and docs/v5_results.csv. Every count is exact (k of n); no rounding to "100%".

Detection rate (no agent) and evasion rate (trained agent) are reported in separate tables.
Part A (agent seeds on cov0-cov3) and Part B (cov1 detector training runs) are separate experiments.
"""

import json
import os
import sys

import pandas as pd

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(ROOT, "code"))
from terminology import label  # noqa: E402

RULES = ["xgboost", "rf", "cnn", "majority", "weighted", "unanimous", "any"]
NAME = {"xgboost": "XGBoost", "rf": "RF", "cnn": "CNN", "majority": "Majority", "weighted": "Weighted",
        "unanimous": "Unanimous", "any": "Any"}
SETS = {"cov0": "cov0 unhardened", "cov1": "cov1 one band each", "cov2": "cov2 two bands each",
        "cov3": "cov3 full hardening"}
DET_RUNS = {"cov1": "model seed 42", "cov1_ms1": "model seed 1", "cov1_ms2": "model seed 2", "cov1_ms3": "model seed 3"}
SIZES = ["64B", "128B", "256B", "512B", "random 1-1460B"]
SEEDS = range(5)


def jload(path):
    with open(os.path.join(ROOT, path)) as f:
        return json.load(f)


def final(set_key):
    return jload(f"code/models_v5/{set_key}/final_eval.json")


def agents(set_key, seed):
    return jload(f"results_v5/agents/{set_key}/seed_{seed}/eval_results.json")


def kn(a, b):
    return f"{a:,} / {b:,}"


def ivl(set_key):
    """Cluster-bootstrap intervals (intervals_v5.py) for one detector set."""
    return jload(f"results_v5/intervals/{set_key}.json")


def ci(c):
    return f"[{c['lo']:.3f}, {c['hi']:.3f}]"


def main():
    L = ["# Results (frozen protocol v5)", "",
         "Generated by `summarize_v5.py` from `final_eval.json` and `eval_results.json` files. Detectors and policies are "
         "frozen (`12_frozen_protocol.md`); every number below is measured on the final-test partition or the final-test "
         "probe bank. Counts are exact. Separation is by invariant-feature groups and does not establish independence "
         "by host, capture session or time. The experiments are constrained flow-feature simulations.", "",
         "**Intervals.** The final-test probe bank holds 13,569 flows but only 72 invariant-feature groups, and flows in a "
         "group are near-identical, so a plain binomial interval would be far too narrow. The 95% intervals in sections 1 "
         "and 2 resample whole groups (probe tables) or whole signatures (clean-traffic tables) with replacement "
         "(`intervals_v5.py`, 2,000 resamples). They describe sampling variation across groups for a fixed, already-trained "
         "detector; they do not include variation from retraining (see section 3 and Part B). An interval of "
         "[1.000, 1.000] means every resampled set of groups was fully detected.", ""]
    csv = []

    # 1 ── detectors on clean final-test traffic
    L += ["## 1. Detectors and rules on clean final-test traffic", "",
          "False positives are benign rows flagged; missed attacks are attack rows not flagged (binary: BENIGN vs everything else).", ""]
    for key, title in SETS.items():
        f = final(key)
        iv = ivl(key)["clean"]
        L += [f"**{title}** ({f['rows']:,} rows)", "", "| Rule | False positives (rate, 95% interval) | Missed attacks (rate, 95% interval) | F1 |", "|---|---|---|---|"]
        for r in RULES:
            m = f["rules"][r]
            fp, ms = iv[r]["false_positive_rate"], iv[r]["missed_attack_rate"]
            L.append(f"| {NAME[r]} | {m['false_positives']:,} ({fp['rate']:.3%}, [{fp['lo']:.3%}, {fp['hi']:.3%}]) | "
                     f"{m['missed_attacks']:,} ({ms['rate']:.3%}, [{ms['lo']:.3%}, {ms['hi']:.3%}]) | {m['binary_f1']:.4f} |")
            csv.append({"table": "clean", "set": key, "rule": r, "false_positives": m["false_positives"],
                        "missed_attacks": m["missed_attacks"], "recall": m["binary_recall"], "f1": m["binary_f1"]})
        L.append("")

    # 2 ── padded-probe detection (no agent)
    L += ["## 2. Padded-probe detection rate (no agent)", "",
          "Flows flagged out of the final-test probe bank, padded to each size, at the simulator's ports 1001-1100.", ""]
    for key, title in SETS.items():
        f = final(key)
        iv = ivl(key)["detection"]
        L += [f"**{title}** ({f['bank_flows']:,} probe flows per cell, 72 groups; 95% group-bootstrap interval in brackets)", "",
              "| Rule | " + " | ".join(SIZES) + " |", "|---|" + "---|" * len(SIZES)]
        for r in RULES:
            cells = []
            for s in SIZES:
                c = f["padded_probe_detection"][r][s]
                cells.append(kn(c["flagged"], c["n"]) + f" {ci(iv[r][s])}")
                csv.append({"table": "detection", "set": key, "rule": r, "size": s, "flagged": c["flagged"], "n": c["n"],
                            "ci_lo": iv[r][s]["lo"], "ci_hi": iv[r][s]["hi"]})
            L.append(f"| {NAME[r]} | " + " | ".join(cells) + " |")
        L.append("")

    # 3 ── Part B detection across the four cov1 training runs
    L += ["## 3. Part B: cov1 across four detector training runs (detection rate, 64 B and 128 B)", "",
          "Each interval is the group-bootstrap interval for that fixed trained detector. The spread *between* the four "
          "training runs is a separate source of variation and is larger than any single interval.", "",
          "| Rule | " + " | ".join(f"{v} 64 B | {v} 128 B" for v in DET_RUNS.values()) + " |",
          "|---|" + "---|---|" * len(DET_RUNS)]
    for r in RULES:
        cells = []
        for key in DET_RUNS:
            f = final(key)
            for s in ("64B", "128B"):
                c = f["padded_probe_detection"][r][s]
                cells.append(kn(c["flagged"], c["n"]) + f" {ci(ivl(key)['detection'][r][s])}")
        L.append(f"| {NAME[r]} | " + " | ".join(cells) + " |")
    L.append("")

    # 4 ── Part A: trained-agent evasion
    L += ["## 4. Part A: trained-agent evasion rate", "",
          "Probes labelled benign out of 2,000 (greedy, 20 episodes, final-test bank), one value per agent seed 0-4. "
          f"Agent types: {label('black', None)} / {label('white', None)}. This is an evasion rate, a different quantity "
          "from the detection rates above.", ""]
    for key, title in SETS.items():
        L += [f"**{title}**", "", f"| Rule | {label('black', None)} (seeds 0-4) | range | {label('white', None)} (seeds 0-4) | range |", "|---|---|---|---|---|"]
        for r in RULES:
            b = [agents(key, s)["trained"][f"{r}_black"]["evaded"] for s in SEEDS]
            w = [agents(key, s)["trained"][f"{r}_white"]["evaded"] for s in SEEDS]
            L.append(f"| {NAME[r]} | {', '.join(f'{x:,}' for x in b)} | {min(b):,}-{max(b):,} | {', '.join(f'{x:,}' for x in w)} | {min(w):,}-{max(w):,} |")
            for s in SEEDS:
                csv.append({"table": "evasion", "set": key, "rule": r, "agent_seed": s,
                            "reward_only_evaded": b[s], "feature_observing_evaded": w[s], "n_probes": 2000})
        L.append("")

    # 5 ── Part B: trained-agent evasion on the cov1 detector training runs
    L += ["## 5. Part B: trained-agent evasion on four cov1 training runs (agent seed 0)", "",
          f"Evaded of 2,000, {label('black', None)} / {label('white', None)}. Separate from Part A: the agent seed is fixed here.", "",
          "| Rule | " + " | ".join(DET_RUNS.values()) + " |", "|---|" + "---|" * len(DET_RUNS)]
    for r in RULES:
        cells = []
        for key in DET_RUNS:
            t = agents(key, 0)["trained"]
            cells.append(f"{t[f'{r}_black']['evaded']:,} / {t[f'{r}_white']['evaded']:,}")
        L.append(f"| {NAME[r]} | " + " | ".join(cells) + " |")
    L.append("")

    # 6 ── untrained baseline
    L += ["## 6. Untrained baseline (uniform random actions, 5,000 probes, seed 0 evaluation)", "",
          "| Rule | " + " | ".join(SETS) + " |", "|---|" + "---|" * len(SETS)]
    for r in RULES:
        cells = []
        for key in SETS:
            u = agents(key, 0)["untrained"][r]
            cells.append(kn(u["evaded"], u["n_probes"]))
        L.append(f"| {NAME[r]} | " + " | ".join(cells) + " |")
    L.append("")

    with open(os.path.join(ROOT, "docs", "v5_results.md"), "w") as f:
        f.write("\n".join(L) + "\n")
    pd.DataFrame(csv).to_csv(os.path.join(ROOT, "docs", "v5_results.csv"), index=False)
    print("Saved docs/v5_results.md, docs/v5_results.csv")


if __name__ == "__main__":
    main()
