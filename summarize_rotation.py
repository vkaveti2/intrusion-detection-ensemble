"""
summarize_rotation.py — CNN band rotation tables (docs/10_band_rotation.md), from final_eval.json files.

Detection of padded probes on the final-test bank, exact counts, for the CNN band assigned (A, B or the cov1
baseline C) within each model seed. Writes docs/band_rotation_summary.md and .csv.
"""

import json
import os
import sys

import pandas as pd

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(ROOT, "code"))
from terminology import label  # noqa: E402
SIZES = ["64B", "128B", "256B", "512B", "random 1-1460B"]
SETS = {1: [("C (baseline)", "cov1_ms1"), ("A", "cov1_cnnA_ms1"), ("B", "cov1_cnnB_ms1")],
        2: [("C (baseline)", "cov1_ms2"), ("A", "cov1_cnnA_ms2"), ("B", "cov1_cnnB_ms2")]}
RULES = [("xgboost", "XGBoost"), ("rf", "RF"), ("cnn", "CNN"), ("unanimous", "Unanimous"), ("majority", "Majority"),
         ("weighted", "Weighted"), ("any", "Any")]


def load(tag):
    with open(os.path.join(ROOT, "code", "models_v5", tag, "final_eval.json")) as f:
        return json.load(f)


def main():
    L = ["# CNN band rotation: detection of padded probes (final-test bank)", "",
         "Generated by `summarize_rotation.py`. Flows flagged out of the final-test probe bank, padded to each size, at the "
         "simulator's ports. Detection rates only (no agent). XGBoost is hardened on band A and RF on band B in every set; "
         "only the CNN's band changes. Design and reading: `10_band_rotation.md`.", ""]
    rows, agent_rows = [], []
    for seed, sets in SETS.items():
        for band, tag in sets:
            f = load(tag)
            n = f["bank_flows"]
            L += [f"## Model seed {seed}, CNN hardened on band {band}", "",
                  "| Rule | " + " | ".join(SIZES) + " |", "|---|" + "---|" * len(SIZES)]
            for r, name in RULES:
                cells = []
                for s in SIZES:
                    c = f["padded_probe_detection"][r][s]
                    cells.append(f"{c['flagged']:,} / {c['n']:,}")
                    rows.append({"model_seed": seed, "cnn_band": band[0], "rule": r, "size": s,
                                 "flagged": c["flagged"], "n": c["n"]})
                L.append(f"| {name} | " + " | ".join(cells) + " |")
            fp = f["detectors"]["cnn"]
            L += ["", f"Clean final-test traffic, CNN alone: {fp['false_positives']:,} false positives "
                  f"({fp['binary_false_positive_rate']:.3%}), {fp['missed_attacks']:,} missed attacks.", ""]
    # trained agents (agent seed 0; CNN and unanimous only, as pre-stated in 10_band_rotation.md)
    L += ["## Trained-agent evasion (agent seed 0)", "",
          "Probes labelled benign out of 2,000 (greedy, final-test bank). Band C rows are the cov1 detector-seed runs from the "
          "main sweep; bands A and B come from `run_v5_rotation_agents.sh`. This is an evasion rate, a different quantity from "
          "the detection rates above. One agent seed per cell.", "",
          f"| Model seed | CNN band | CNN {label('black', None)} | CNN {label('white', None)} | Unanimous {label('black', None)} | "
          f"Unanimous {label('white', None)} | Payload chosen, {label('black', None)} agent (CNN / unanimous) |",
          "|---|---|---|---|---|---|---|"]
    for seed in (1, 2):
        for band, d in (("C (baseline)", f"results_v5/agents/cov1_ms{seed}/seed_0"),
                        ("A", f"results_v5/rotation/agents/cov1_cnnA_ms{seed}"),
                        ("B", f"results_v5/rotation/agents/cov1_cnnB_ms{seed}")):
            with open(os.path.join(ROOT, d, "eval_results.json")) as fh:
                t = json.load(fh)["trained"]
            top = lambda k: max(t[k]["payload_choice"].items(), key=lambda kv: kv[1])
            L.append(f"| {seed} | {band} | {t['cnn_black']['evaded']:,} | {t['cnn_white']['evaded']:,} | "
                     f"{t['unanimous_black']['evaded']:,} | {t['unanimous_white']['evaded']:,} | "
                     f"{top('cnn_black')[0]} B ({top('cnn_black')[1]:.0%}) / {top('unanimous_black')[0]} B ({top('unanimous_black')[1]:.0%}) |")
            agent_rows.append({"model_seed": seed, "cnn_band": band[0], "n_probes": 2000,
                               "cnn_reward_only_evaded": t["cnn_black"]["evaded"],
                               "cnn_feature_observing_evaded": t["cnn_white"]["evaded"],
                               "unanimous_reward_only_evaded": t["unanimous_black"]["evaded"],
                               "unanimous_feature_observing_evaded": t["unanimous_white"]["evaded"]})
    L.append("")
    with open(os.path.join(ROOT, "docs", "band_rotation_summary.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    pd.DataFrame(rows).to_csv(os.path.join(ROOT, "docs", "band_rotation_summary.csv"), index=False)
    pd.DataFrame(agent_rows).to_csv(os.path.join(ROOT, "docs", "band_rotation_agents.csv"), index=False)
    print("Saved docs/band_rotation_summary.md, .csv and band_rotation_agents.csv")


if __name__ == "__main__":
    main()
