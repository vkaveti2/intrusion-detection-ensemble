"""
summarize_benchmark.py — tables from results_v5/benchmark/benchmark_<label>_<set>.json (docs/13_edge_benchmark.md).

One section per host and detector set: latency percentiles, throughput, memory, slowdown against the named baseline,
the stage breakdown, and the consistency checks. Reads every result file it finds, so results from additional
machines appear without editing this script. Writes docs/13_benchmark_results.md and docs/13_benchmark_results.csv.
"""

import glob
import json
import os

import pandas as pd

ROOT = os.path.dirname(os.path.abspath(__file__))
BENCH = os.path.join(ROOT, "results_v5", "benchmark")
CONFIGS = ["xgboost", "rf", "cnn", "majority", "weighted", "unanimous", "any"]
NAME = {"xgboost": "XGBoost", "rf": "RF", "cnn": "CNN", "majority": "Majority", "weighted": "Weighted",
        "unanimous": "Unanimous", "any": "Any"}


def host_line(h):
    parts = [h.get("device_model") or h.get("cpu"), h.get("machine"), f"{h.get('cpu_count')} logical CPUs"]
    if h.get("memory_gb"):
        parts.append(f"{h['memory_gb']} GB RAM")
    parts.append(f"Python {h['python']}")
    parts.append(f"OMP_NUM_THREADS={h.get('OMP_NUM_THREADS')}")
    return ", ".join(str(p) for p in parts if p)


def main():
    files = sorted(glob.glob(os.path.join(BENCH, "benchmark_*.json")))
    if not files:
        raise SystemExit(f"no result files in {BENCH}")
    L = ["# Inference cost results (RQ3)", "",
         "Generated by `summarize_benchmark.py` from `results_v5/benchmark/*.json`. Method, what is and is not measured, "
         "and the procedure: `13_edge_benchmark.md`. **Every figure is inference time on a 77-feature flow record; packet "
         "capture and flow-feature extraction are not included.** Slowdown is relative to the named baseline (standalone "
         "XGBoost): latency and memory as configuration / baseline, throughput as baseline / configuration, so a value above "
         "1.00x is worse than the baseline.", ""]
    rows = []
    for path in files:
        r = json.load(open(path))
        res, sd, b = r["results"], r["slowdown_vs_baseline"], r["baseline"]
        s = r["settings"]
        L += [f"## {r['label']}: detector set {r['detector_set']}", "",
              f"Host: {host_line(r['host'])}. Run {r['timestamp']}. {s['repeats']} repeats x {s['flows_per_repeat']:,} flows "
              f"(batch size 1), median over repeats. Baseline: {NAME[b]}.", ""]
        L += ["| Configuration | p50 ms | p90 ms | p95 ms | p99 ms | max ms | p50 vs baseline | p99 vs baseline |",
              "|---|---|---|---|---|---|---|---|"]
        for c in CONFIGS:
            x = res[c]["latency_ms"]
            L.append(f"| {NAME[c]} | {x['p50']:.3f} | {x['p90']:.3f} | {x['p95']:.3f} | {x['p99']:.3f} | {x['max']:.3f} | "
                     f"{sd[c]['p50_latency_x']:.2f}x | {sd[c]['p99_latency_x']:.2f}x |")
        L += ["", "Batched throughput caveat: the CNN's batched figure is lower than its single-flow figure on the development machine "
              "(a slow CPU convolution path in PyTorch at batch size 16 and above, not a property of the model; see "
              "`13_edge_benchmark.md`). The batch-size-1 results above are the primary measurement; the batched columns for "
              "the CNN and the ensembles that contain it are platform-specific.", "",
              "| Configuration | Single-stream flows/s | Batched (256) flows/s | Throughput vs baseline (single / batched) | "
              "Peak memory MB | Added by models MB | Memory vs baseline |", "|---|---|---|---|---|---|---|"]
        for c in CONFIGS:
            x = res[c]
            L.append(f"| {NAME[c]} | {x['single_stream_flows_per_s']:,.0f} | {x['batched_flows_per_s']:,.0f} | "
                     f"{sd[c]['single_stream_throughput_x']:.2f}x / {sd[c]['batched_throughput_x']:.2f}x | "
                     f"{x['memory_mb']['peak']:,.0f} | {x['memory_mb']['added_by_models']:,.0f} | {sd[c]['peak_memory_x']:.2f}x |")
            rows.append({"label": r["label"], "set": r["detector_set"], "config": c, **{f"lat_{k}_ms": v for k, v in x["latency_ms"].items()},
                         "single_flows_per_s": x["single_stream_flows_per_s"], "batched_flows_per_s": x["batched_flows_per_s"],
                         "peak_mb": x["memory_mb"]["peak"], "added_mb": x["memory_mb"]["added_by_models"],
                         "p50_x": sd[c]["p50_latency_x"], "p99_x": sd[c]["p99_latency_x"],
                         "peak_memory_x": sd[c]["peak_memory_x"]})
        L += ["", "Where the mean time goes (ms per flow; staged pass):", "",
              "| Configuration | Scaling | Model call(s) | Vote | Other | Mean end-to-end |", "|---|---|---|---|---|---|"]
        for c in CONFIGS:
            st = res[c]["stages_ms_mean"]
            L.append(f"| {NAME[c]} | {st['scale']:.3f} | {st['model']:.3f} | {st['vote']:.4f} | {st['unattributed']:.3f} | "
                     f"{res[c]['latency_ms']['mean']:.3f} |")
        f = res["features"]
        L += ["", f"Payload-to-feature recomputation (a proxy for the arithmetic, not for flow-feature extraction): "
              f"p50 {f['latency_ms']['p50']:.4f} ms, p99 {f['latency_ms']['p99']:.4f} ms.", ""]
        ok = all(res[c]["agreement"]["staged_vs_end_to_end"][0] == res[c]["agreement"]["staged_vs_end_to_end"][1] and
                 res[c]["agreement"]["batched_vs_single_flow"][0] == res[c]["agreement"]["batched_vs_single_flow"][1]
                 for c in CONFIGS)
        a = res["majority"]["agreement"]
        L += [f"Consistency checks: staged decisions equal end-to-end decisions and batched decisions equal single-flow "
              f"decisions in every configuration ({'yes' if ok else '**NO, see the result file**'}; majority: staged "
              f"{a['staged_vs_end_to_end'][0]:,} of {a['staged_vs_end_to_end'][1]:,}, batched {a['batched_vs_single_flow'][0]:,} of "
              f"{a['batched_vs_single_flow'][1]:,}).", ""]
        th = [t.get("throttled") for t in r["thermal"] if t.get("throttled")]
        if th:
            L += [f"Throttle flags sampled: {sorted(set(th))}.", ""]
    with open(os.path.join(ROOT, "docs", "13_benchmark_results.md"), "w") as f:
        f.write("\n".join(L) + "\n")
    pd.DataFrame(rows).to_csv(os.path.join(ROOT, "docs", "13_benchmark_results.csv"), index=False)
    print(f"Saved docs/13_benchmark_results.md, docs/13_benchmark_results.csv ({len(files)} result file(s))")


if __name__ == "__main__":
    main()
