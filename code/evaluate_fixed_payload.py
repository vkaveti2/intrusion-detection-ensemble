"""
evaluate_fixed_payload.py — DDQN against the best fixed payload choice (frozen protocol v5).

The interface has 1,250 actions (50 delays x 5 flag options x 5 payload sizes), but in the
constrained flow-feature simulation only the payload size changes the detector input: flags keep the
real flow's recorded values and delay only enters the reward. So a policy that always sends one
payload size at the smallest delay is the natural no-learning comparator.

Selection uses development data only:
  1. For each detector set and rule, count the evasions at each of the five payload sizes on the DEV
     probe bank (validation_eval.json, written by evaluate_v5.py --stage weights). Choose the size with
     the most evasions; ties go to the smallest size.
  2. Report that size's evasion on the FINAL-TEST bank (final_eval.json), exact k of n.
  3. Report the full five-choice final-test evasion as the reference (including the size that is best
     on final test, which the dev choice may miss).
  4. Compare with the trained DDQN agents' greedy evasion (eval_results.json, 2,000 probes per run).

Reward: +1 - 0.1*delay/100 for an evaded probe, -1 for a detected one (ids_env). The fixed policy uses
the smallest delay (0.1). The DDQN reward is ESTIMATED from its evasion rate and median chosen delay;
the evaluation stored the median, not the per-probe reward.

Writes docs/fixed_payload_summary.md and docs/fixed_payload_summary.csv.   python evaluate_fixed_payload.py
"""

import json
import os
import sys

import numpy as np
import pandas as pd

os.environ["OMP_NUM_THREADS"] = "1"
CODE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(CODE)
sys.path.insert(0, CODE)
from ids_env import DELAY_OPTIONS, MAX_DELAY, PENALTY_WEIGHT  # noqa: E402
from terminology import label  # noqa: E402

RULES = ["xgboost", "rf", "cnn", "majority", "weighted", "unanimous", "any"]
NAME = {"xgboost": "XGBoost", "rf": "RF", "cnn": "CNN", "majority": "Majority", "weighted": "Weighted",
        "unanimous": "Unanimous", "any": "Any"}
SETS = {"cov0": "cov0 unhardened", "cov1": "cov1 one band each", "cov2": "cov2 two bands each",
        "cov3": "cov3 full hardening"}
SIZES = ["0B", "64B", "128B", "256B", "512B"]
SEEDS = range(5)
MIN_DELAY = float(min(DELAY_OPTIONS))


def jload(path):
    with open(os.path.join(ROOT, path)) as f:
        return json.load(f)


def reward(evade_rate, delay):
    return evade_rate * (1 - PENALTY_WEIGHT * delay / MAX_DELAY) - (1 - evade_rate)


def evaded(cell):
    return cell["n"] - cell["flagged"], cell["n"]


def main():
    rows, L = [], ["# Fixed-payload comparison (frozen protocol v5)", "",
                   "Generated by `evaluate_fixed_payload.py`. A constrained flow-feature simulation: of the 1,250 actions "
                   "only the five payload sizes change what the detectors see (flags are not simulated; delay only affects "
                   "reward). The fixed policy sends one payload size at the smallest delay "
                   f"({MIN_DELAY:g}). The size is **chosen on the dev bank** (14 groups) and **evaluated on the final-test "
                   "bank** (72 groups, 13,569 flows). Ties go to the smallest size. The DDQN agents train on the "
                   "agent-train bank and are evaluated greedily on the final-test bank (2,000 probes per run). Counts are "
                   "exact; reward for the DDQN agents is an estimate from its median delay.", ""]
    for key, title in SETS.items():
        dev = jload(f"code/models_v5/{key}/validation_eval.json")["padded_probe_detection"]
        fin = jload(f"code/models_v5/{key}/final_eval.json")["padded_probe_detection"]
        ev = [jload(f"results_v5/agents/{key}/seed_{s}/eval_results.json")["trained"] for s in SEEDS]
        L += [f"## {title}", "", "| Rule | Dev: evaded at 0/64/128/256/512 B (of 3,816) | Chosen size | "
              "Final test: chosen size | Final test: best of five | "
              f"DDQN {label('black', None)} (mean, range of 5 seeds) | DDQN {label('white', None)} (mean, range) |",
              "|---|---|---|---|---|---|---|"]
        for r in RULES:
            dev_ev = [evaded(dev[r][s])[0] for s in SIZES]
            n_dev = evaded(dev[r]["0B"])[1]
            pick = SIZES[int(np.argmax(dev_ev))]                    # argmax returns the first max = smallest size
            fin_ev = {s: evaded(fin[r][s]) for s in SIZES}
            k_pick, n_fin = fin_ev[pick]
            best_s = max(SIZES, key=lambda s: (fin_ev[s][0], -SIZES.index(s)))
            k_best = fin_ev[best_s][0]
            cells = {}
            for knd in ("black", "white"):
                k = [e[f"{r}_{knd}"]["evaded"] for e in ev]
                cells[knd] = (k, [e[f"{r}_{knd}"]["median_delay_s"] for e in ev])
            ddqn_txt = lambda k: f"{np.mean(k) / 2000:.1%} ({min(k):,}-{max(k):,} of 2,000)"
            L.append(f"| {NAME[r]} | {', '.join(f'{x:,}' for x in dev_ev)} | {pick} | "
                     f"{k_pick:,} / {n_fin:,} ({k_pick / n_fin:.1%}) | {best_s}: {k_best:,} / {n_fin:,} ({k_best / n_fin:.1%}) | "
                     f"{ddqn_txt(cells['black'][0])} | {ddqn_txt(cells['white'][0])} |")
            row = {"set": key, "rule": r, "dev_chosen_size": pick, "dev_evaded": dev_ev, "dev_n": n_dev,
                   "fixed_final_evaded": k_pick, "final_n": n_fin, "final_best_size": best_s, "final_best_evaded": k_best,
                   "fixed_reward": reward(k_pick / n_fin, MIN_DELAY)}
            for s in SIZES:
                row[f"final_evaded_{s}"] = fin_ev[s][0]
            for knd, nm in (("black", "reward_only"), ("white", "feature_observing")):
                k, d = cells[knd]
                row[f"ddqn_{nm}_evaded_mean_of_2000"] = float(np.mean(k))
                row[f"ddqn_{nm}_evaded_min"], row[f"ddqn_{nm}_evaded_max"] = min(k), max(k)
                row[f"ddqn_{nm}_median_delay_s"] = float(np.median(d))
                row[f"ddqn_{nm}_reward_estimate"] = float(np.mean([reward(x / 2000, dd) for x, dd in zip(k, d)]))
            rows.append(row)
        L.append("")

    # reference: the full five-choice evaluation on the final-test bank
    L += ["## Reference: all five payload choices on the final-test bank", "",
          "Evaded flows out of 13,569, by payload size. The best fixed choice on final test is the maximum of each row; "
          "the dev-chosen size can differ from it.", ""]
    for key, title in SETS.items():
        L += [f"**{title}**", "", "| Rule | 0 B | 64 B | 128 B | 256 B | 512 B |", "|---|---|---|---|---|---|"]
        for r in RULES:
            row = next(x for x in rows if x["set"] == key and x["rule"] == r)
            L.append(f"| {NAME[r]} | " + " | ".join(f"{row[f'final_evaded_{s}']:,}" for s in SIZES) + " |")
        L.append("")

    # reward
    L += ["## Reward (estimate for the DDQN agents)", "",
          f"Fixed policy: smallest delay ({MIN_DELAY:g}), so the delay penalty is {PENALTY_WEIGHT * MIN_DELAY / MAX_DELAY:.4f} per evaded "
          "probe. DDQN: estimated from its evasion rate and median chosen delay. Mean over the five agent seeds.", "",
          f"| Set | Rule | Fixed (dev choice) | DDQN {label('black', None)} | DDQN {label('white', None)} | Median delay {label('black', None)} / {label('white', None)} (s) |",
          "|---|---|---|---|---|---|"]
    for x in rows:
        if x["fixed_final_evaded"] == 0 and x["ddqn_reward_only_evaded_max"] == 0 and x["ddqn_feature_observing_evaded_max"] == 0:
            continue
        L.append(f"| {x['set']} | {NAME[x['rule']]} | {x['fixed_reward']:.4f} | {x['ddqn_reward_only_reward_estimate']:.4f} | "
                 f"{x['ddqn_feature_observing_reward_estimate']:.4f} | {x['ddqn_reward_only_median_delay_s']:.2f} / "
                 f"{x['ddqn_feature_observing_median_delay_s']:.2f} |")
    L += ["", "Rows where nothing evades (fixed policy and every DDQN run at 0) are omitted; their reward is -1 for all.", ""]

    with open(os.path.join(ROOT, "docs", "fixed_payload_summary.md"), "w") as f:
        f.write("\n".join(L) + "\n")
    pd.DataFrame(rows).to_csv(os.path.join(ROOT, "docs", "fixed_payload_summary.csv"), index=False)
    print("Saved docs/fixed_payload_summary.md, docs/fixed_payload_summary.csv")


if __name__ == "__main__":
    main()
